CREATE TABLE sale_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT NOT NULL,
    transaction_date TIMESTAMP WITH TIME ZONE NOT NULL,
    sale_amount NUMERIC(19, 4) NOT NULL,
    status VARCHAR(16) NOT NULL,
    CONSTRAINT sale_transaction_merchant_fk FOREIGN KEY (merchant_id) REFERENCES merchant (id),
    CONSTRAINT sale_transaction_status_check CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED'))
);

CREATE INDEX sale_transaction_merchant_date_idx
    ON sale_transaction (merchant_id, transaction_date);

CREATE INDEX sale_transaction_pending_idx
    ON sale_transaction (merchant_id);

CREATE TABLE click_daily (
    merchant_id BIGINT NOT NULL,
    click_date DATE NOT NULL,
    click_count INTEGER NOT NULL,
    CONSTRAINT click_daily_pk PRIMARY KEY (merchant_id, click_date),
    CONSTRAINT click_daily_merchant_fk FOREIGN KEY (merchant_id) REFERENCES merchant (id)
);
