CREATE TABLE merchant (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    currency VARCHAR(3) NOT NULL
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    CONSTRAINT app_user_username_unique UNIQUE (username)
);

CREATE TABLE user_merchant (
    user_id BIGINT NOT NULL,
    merchant_id BIGINT NOT NULL,
    CONSTRAINT user_merchant_pk PRIMARY KEY (user_id, merchant_id),
    CONSTRAINT user_merchant_user_fk FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT user_merchant_merchant_fk FOREIGN KEY (merchant_id) REFERENCES merchant (id)
);
