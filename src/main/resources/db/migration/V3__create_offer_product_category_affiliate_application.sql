CREATE TABLE offer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(16) NOT NULL,
    CONSTRAINT offer_merchant_fk FOREIGN KEY (merchant_id) REFERENCES merchant (id),
    CONSTRAINT offer_status_check CHECK (status IN ('ACTIVE', 'REMOVED'))
);

CREATE INDEX offer_merchant_status_expires_idx
    ON offer (merchant_id, status, expires_at);

CREATE TABLE product_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT NOT NULL,
    mapped BOOLEAN NOT NULL,
    CONSTRAINT product_category_merchant_fk FOREIGN KEY (merchant_id) REFERENCES merchant (id)
);

CREATE INDEX product_category_merchant_mapped_idx
    ON product_category (merchant_id, mapped);

CREATE TABLE affiliate_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    CONSTRAINT affiliate_application_merchant_fk FOREIGN KEY (merchant_id) REFERENCES merchant (id),
    CONSTRAINT affiliate_application_status_check CHECK (status IN ('PENDING', 'REVIEWED'))
);

CREATE INDEX affiliate_application_merchant_status_idx
    ON affiliate_application (merchant_id, status);
